class Solution:
    def kidsWithCandies(self, candies: List[int], extraCandies: int) -> List[bool]:
        maxCanditate=max(candies)
        for i in range(len(candies)):
            s=candies[i]+extraCandies
            if s>=maxCanditate:
                candies[i]=True
            else:
                candies[i]=False
        return candies



















































































































